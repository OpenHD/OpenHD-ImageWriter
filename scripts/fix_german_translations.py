def main():
    path = Path(__file__).resolve().parents[1] / "src/i18n/rpi-imager_de.ts"
    tree = ET.parse(path)
    changed = 0
    for message in tree.findall("context/message"):
        source = message.findtext("source")
        if source not in TRANSLATIONS:
            continue
        translation = message.find("translation")
        if translation is None:
            translation = ET.SubElement(message, "translation")
        if translation.text != TRANSLATIONS[source] or translation.get("type"):
            translation.text = TRANSLATIONS[source]
            translation.attrib.pop("type", None)
            changed += 1
    ET.indent(tree, space="    ")
    path.write_text('<?xml version="1.0" encoding="utf-8"?>\n<!DOCTYPE TS>\n' + ET.tostring(tree.getroot(), encoding="unicode") + '\n', encoding="utf-8")
    print(f"Updated {changed} German translations")


if __name__ == "__main__":
    main()
